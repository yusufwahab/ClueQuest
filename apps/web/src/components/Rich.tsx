import { useEffect, useState, type ReactNode } from 'react';
import { API_BASE } from '../lib/api';
import { Modal } from './ui';

/**
 * Question text with maths and pictures.
 *  - Maths is written between dollar signs, the way most teachers already know it: $x^2 + 3x$ inline, $$\frac{a}{b}$$ on its own line.
 *  - The maths engine (KaTeX) is only downloaded when a page actually contains maths, so ordinary quizzes stay light.
 *  - Everything else is shown as plain text, never as HTML, so a question can't inject markup.
 */

export type Seg = { k: 'text'; v: string } | { k: 'math'; v: string; display: boolean };

/** Where a maths section that opens at `from` ends, or -1 if it is not maths ("$5 and $10" and "costs $5." are just money). */
function findClose(s: string, from: number, display: boolean): number {
  if (from >= s.length || (!display && /\s/.test(s[from]!))) return -1; // "$ 5" is not maths
  for (let j = from; j < s.length; j++) {
    const c = s[j]!;
    if (c === '\\') { j++; continue; } // skip \$ and commands like \frac
    if (c !== '$') continue;
    if (display) { if (s[j + 1] === '$') return j > from ? j : -1; continue; }
    const before = s[j - 1] ?? '', after = s[j + 1] ?? '';
    if (/\s/.test(before) && after !== '' && !/\s/.test(after)) return -1; // looks like another opening dollar: the first one was money
    if (/\s/.test(before) || /\d/.test(after)) continue;
    return j > from ? j : -1;
  }
  return -1;
}

export function splitMath(src: string): Seg[] {
  const out: Seg[] = [];
  let buf = '';
  const flush = () => { if (buf) { out.push({ k: 'text', v: buf }); buf = ''; } };
  for (let i = 0; i < src.length;) {
    const c = src[i]!;
    if (c === '\\' && src[i + 1] === '$') { buf += '$'; i += 2; continue; } // \$ is a literal dollar sign
    if (c === '$') {
      const display = src[i + 1] === '$';
      const open = i + (display ? 2 : 1);
      const close = findClose(src, open, display);
      if (close > -1) { flush(); out.push({ k: 'math', v: src.slice(open, close), display }); i = close + (display ? 2 : 1); continue; }
    }
    buf += c; i++;
  }
  flush();
  return out;
}

export const hasMath = (s: string) => splitMath(s).some((x) => x.k === 'math');

type Katex = typeof import('katex').default;
let loader: Promise<Katex> | null = null;
function loadKatex(): Promise<Katex> {
  loader ??= Promise.all([import('katex'), import('katex/dist/katex-swap.min.css')]).then(([m]) => m.default);
  return loader;
}
const cache = new Map<string, string>();

function Tex({ tex, display }: { tex: string; display: boolean }) {
  const key = `${display ? 'D' : 'I'}:${tex}`;
  const [html, setHtml] = useState<string | null>(cache.get(key) ?? null);
  useEffect(() => {
    if (cache.has(key)) { setHtml(cache.get(key)!); return; }
    let live = true;
    void loadKatex().then((k) => {
      const out = k.renderToString(tex, { displayMode: display, throwOnError: false, strict: 'ignore', trust: false, output: 'htmlAndMathml', maxExpand: 1000, maxSize: 20 });
      cache.set(key, out);
      if (live) setHtml(out);
    }).catch(() => { /* if the maths engine cannot load, the raw text below stays readable */ });
    return () => { live = false; };
  }, [key, tex, display]);
  // Until it loads, show the source so nothing is ever blank. KaTeX's own markup is generated by the library, not taken from the question.
  if (html == null) return <span className="font-mono text-[0.9em]">{display ? `$$${tex}$$` : `$${tex}$`}</span>;
  return display
    ? <span className="my-1 block overflow-x-auto overflow-y-hidden" dangerouslySetInnerHTML={{ __html: html }} />
    : <span dangerouslySetInnerHTML={{ __html: html }} />;
}

/** Text with maths. `inline` keeps display maths on the same line (for answer options and small labels). */
export function Rich({ text, inline = false, className }: { text: string; inline?: boolean; className?: string }): ReactNode {
  if (!text.includes('$')) return <span className={`whitespace-pre-line ${className ?? ''}`}>{text}</span>;
  return (
    <span className={`whitespace-pre-line ${className ?? ''}`}>
      {splitMath(text).map((s, i) => (s.k === 'text' ? <span key={i}>{s.v}</span> : <Tex key={i} tex={s.v} display={s.display && !inline} />))}
    </span>
  );
}

export type PictureRef = { id: string; alt: string; url?: string | null };
/** Where to load a picture from. Cloudinary addresses are absolute; our own are relative to the server, which may be on another site. */
export const imageSrc = (img: PictureRef) => (img.url ? (img.url.startsWith('/') ? `${API_BASE}${img.url}` : img.url) : `${API_BASE}/api/images/${img.id}`);

/** The picture that belongs to a question. Tap it to see it larger. Lazy-loaded, and cached for a year by the browser (the server marks it immutable). */
export function QuestionImage({ image, className = 'max-h-72' }: { image: PictureRef | null | undefined; className?: string }) {
  const [big, setBig] = useState(false);
  if (!image) return null;
  return (
    <>
      <button type="button" onClick={() => setBig(true)} className="block max-w-full rounded-xl focus-visible:outline-offset-4" aria-label={`Enlarge picture${image.alt ? `: ${image.alt}` : ''}`}>
        <img src={imageSrc(image)} alt={image.alt} loading="lazy" decoding="async" className={`${className} w-auto max-w-full rounded-xl border-2 border-line bg-white object-contain`} />
      </button>
      {big && (
        <Modal title="Picture" onClose={() => setBig(false)} wide>
          <img src={imageSrc(image)} alt={image.alt} className="mx-auto max-h-[70vh] w-auto max-w-full rounded-xl object-contain" />
          {image.alt && <p className="hint mt-3">{image.alt}</p>}
        </Modal>
      )}
    </>
  );
}
